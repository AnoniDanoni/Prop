        private static double ObterMto(LinhaDados linha)
        {
            if (!linha.Cylinder) return 1d;
            Match numero = Regex.Match(linha.Propriedades[1] ?? "", @"[-+]?\d+(?:[.,]\d+)?");
            if (!numero.Success || !double.TryParse(numero.Value.Replace(',', '.'), NumberStyles.Float,
                CultureInfo.InvariantCulture, out double milimetros)) return 0d;
            return Math.Round(milimetros / 1000d, 3);
        }

        public override int ExecuteCommand(string commandId, params string[] parameters)
